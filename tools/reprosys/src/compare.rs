    /// `text` as `bootconfig -a` writes it, with its footer.
    fn bootconfig(text: &str) -> Vec<u8> {
        let mut out = text.as_bytes().to_vec();
        out.resize(out.len().next_multiple_of(4), 0);
        let checksum: u32 = out.iter().map(|b| u32::from(*b)).sum();
        out.extend((out.len() as u32).to_le_bytes());
        out.extend(checksum.to_le_bytes());
        out.extend(b"#BOOTCONFIG\n");
        out
    }

