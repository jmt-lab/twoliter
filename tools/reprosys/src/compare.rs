struct Images {
    expected: File,
    actual: File,
    expected_path: PathBuf,
    actual_path: PathBuf,
}

impl Images {
    fn open(expected: &Path, actual: &Path) -> Result<Self> {
        let open =
            |p: &Path| File::open(p).whatever_context(format!("failed to open {}", p.display()));
        Ok(Self {
            expected: open(expected)?,
            actual: open(actual)?,
            expected_path: expected.to_path_buf(),
            actual_path: actual.to_path_buf(),
        })
    }

    fn hash(&mut self, ranges: &[(u64, u64)]) -> Result<(RangeHash, RangeHash)> {
        Ok((
            disk::hash_ranges(&mut self.expected, ranges)?,
            disk::hash_ranges(&mut self.actual, ranges)?,
        ))
    }

    fn read(&mut self, p: &Partition) -> Result<(Vec<u8>, Vec<u8>)> {
        Ok((
            disk::read_range(&mut self.expected, p.offset, p.len)?,
            disk::read_range(&mut self.actual, p.offset, p.len)?,
        ))
    }
}

fn assess_region(
    name: &str,
    policy: Policy,
    ranges: &[(u64, u64)],
    expected: Option<&RangeHash>,
    actual: &RangeHash,
) -> RegionReport {
    let offset = ranges.first().map(|r| r.0).unwrap_or(0);
    let len = ranges.iter().map(|r| r.1).sum();
    let identical = expected.is_none_or(|e| e == actual);
    let (status, detail) = match policy {
        Policy::MustBeZero if !actual.all_zero => {
            (Status::Mismatch, "published image is not all zero")
        }
        _ if identical => (Status::Match, "identical"),
        _ => (Status::Mismatch, "contents differ"),
    };
    let _scope = eventlog::region(name);
    eventlog::event(
        "bytes",
        json!({
            "policy": policy,
            "ranges": ranges,
            "rebuilt_sha256": expected.map(RangeHash::hex),
            "published_sha256": actual.hex(),
            "published_all_zero": actual.all_zero,
            "status": status,
        }),
    );
    RegionReport {
        name: name.to_string(),
        policy,
        status,
        fatal: true,
        offset,
        len,
        expected_sha256: expected.map(RangeHash::hex),
        actual_sha256: Some(actual.hex()),
        detail: detail.to_string(),
        files: Vec::new(),
    }
}

/// Compare partition-by-partition two images that share a GPT layout.
pub fn compare_os(expected: &Path, actual: &Path) -> Result<ImageReport> {
    let mut images = Images::open(expected, actual)?;
    let expected_len = disk::file_len(&images.expected)?;
    let actual_len = disk::file_len(&images.actual)?;
    let mut report = ImageReport {
        expected: Some(expected.to_path_buf()),
        actual: Some(actual.to_path_buf()),
        expected_len,
        actual_len,
        regions: Vec::new(),
    };
    eventlog::event(
        "image",
        json!({
            "image": "os",
            "rebuilt": expected,
            "published": actual,
            "rebuilt_len": expected_len,
            "published_len": actual_len,
        }),
    );

    if actual_len < expected_len {
        report.regions.push(RegionReport {
            name: "SIZE".to_string(),
            policy: Policy::MustMatch,
            status: Status::Mismatch,
            fatal: true,
            offset: 0,
            len: expected_len,
            expected_sha256: None,
            actual_sha256: None,
            detail: format!(
                "published image ({actual_len} bytes) is smaller than the rebuilt image ({expected_len} bytes)"
            ),
            files: Vec::new(),
        });
        return Ok(report);
    }

    let layout = DiskLayout::read(&mut images.expected)?;
    eventlog::event(
        "layout",
        json!({
            "primary_gpt_end": layout.primary_gpt_end,
            "backup_gpt": layout.backup_gpt,
            "partitions": layout.partitions.iter().map(|p| json!({
                "name": p.name,
                "offset": p.offset,
                "len": p.len,
                "policy": p.policy(),
            })).collect::<Vec<_>>(),
            "unallocated": layout.unallocated(expected_len),
        }),
    );
    let gpt_ranges = layout.gpt_ranges();
    let (e, a) = images.hash(&gpt_ranges)?;
    let mut gpt = assess_region("GPT", Policy::MustMatch, &gpt_ranges, Some(&e), &a);
    gpt.detail = match gpt.status {
        Status::Match => "protective MBR, primary and backup GPT identical".to_string(),
        _ => "partition tables differ; partition comparisons use the rebuilt layout".to_string(),
    };
    report.regions.push(gpt);

    let gaps = layout.unallocated(expected_len);
    if !gaps.is_empty() {
        let (e, a) = images.hash(&gaps)?;
        report.regions.push(assess_region(
            "UNALLOCATED",
            Policy::MustMatch,
            &gaps,
            Some(&e),
            &a,
        ));
    }

    let boot_source = BootSource::of(&layout);
    let mut boot_config = BootConfig::unread(boot_source);
    for p in &layout.partitions {
        let policy = p.policy();
        let ranges = [(p.offset, p.len)];
        let (e, a) = images.hash(&ranges)?;
        let mut r = assess_region(&p.name, policy, &ranges, Some(&e), &a);
        match policy {
            Policy::MustMatch if p.name == "PRIVATE" && r.status != Status::Match => {
                explain_private(&mut images, p, &mut r)
            }
            Policy::MustMatch | Policy::MustBeZero | Policy::BootConfig => {}
            Policy::SaltDependent => {
                r.fatal = false;
                if r.status != Status::Match {
                    r.status = Status::ExpectedDifference;
                    r.detail = "differs; depends on the random verity salt and is not compared"
                        .to_string();
                }
            }
            Policy::FilesMustMatch if r.status != Status::Match => {
                compare_root(&images, p, &mut r)?
            }
            Policy::FilesMustMatch => {}
            Policy::SigningDependent => {
                let (exp, act) = images.read(p)?;
                let files = if p.name == "EFI-A" {
                    fsfiles::fat_files(exp).and_then(|e| Ok((e, fsfiles::fat_files(act)?)))
                } else {
                    fsfiles::ext4_files(exp).and_then(|e| Ok((e, fsfiles::ext4_files(act)?)))
                };
                let _scope = eventlog::region(&p.name);
                match files {
                    Ok((exp, act)) => {
                        let summary = |files: &fsfiles::Files| {
                            json!({
                                "files": files.len(),
                                "bytes": files.values().map(|f| f.len() as u64).sum::<u64>(),
                            })
                        };
                        eventlog::event(
                            "files-read",
                            json!({ "rebuilt": summary(&exp), "published": summary(&act) }),
                        );
                        if p.name == boot_source.partition() {
                            boot_config = BootConfig::read(boot_source, &exp, &act);
                        }
                        if r.status != Status::Match {
                            explain_boot_files(&exp, &act, &mut r);
                        }
                    }
                    Err(e) => {
                        eventlog::event("error", json!({ "error": e.to_string() }));
                        // A partition that differs must be compared to be accepted.
                        if r.status != Status::Match {
                            r.detail = format!("contents differ and files could not be read: {e}");
                        }
                    }
                }
            }
        }
        report.regions.push(r);
    }

    // Needs BOOT-A or EFI-A to have been read.
    if layout.find("HASH-A").is_some() {
        let _scope = eventlog::region("BOOT-CONFIG");
        let result = check_boot_config(&boot_config);
        if let Err(e) = &result {
            eventlog::event("error", json!({ "error": e.to_string() }));
        }
        report.regions.push(boot_config_region(
            layout.find(boot_source.partition()),
            &boot_config,
            &result,
        ));
    }

    if actual_len > expected_len {
        let tail = [(expected_len, actual_len - expected_len)];
        let a = disk::hash_ranges(&mut images.actual, &tail)?;
        let mut r = assess_region("PADDING", Policy::MustBeZero, &tail, None, &a);
        if r.status == Status::Match {
            r.detail = "bytes beyond the rebuilt image are zero".to_string();
        }
        report.regions.push(r);
    }

    Ok(report)
}

/// Compare a ROOT-A whose bytes differ file by file. Only erofs is supported;
/// any other ROOT-A that differs fails.
fn compare_root(images: &Images, p: &Partition, r: &mut RegionReport) -> Result<()> {
    let fs_name = |erofs: bool| if erofs { "erofs" } else { "not erofs" };
    let _scope = eventlog::region(&p.name);
    let expected_erofs = erofs::is_erofs(&images.expected, p.offset)?;
    let actual_erofs = erofs::is_erofs(&images.actual, p.offset)?;
    eventlog::event(
        "filesystem",
        json!({ "rebuilt": fs_name(expected_erofs), "published": fs_name(actual_erofs) }),
    );
    if !(expected_erofs && actual_erofs) {
        r.detail = format!(
            "the rebuilt ROOT-A is {} and the published ROOT-A is {}; only erofs root \
             filesystems are supported, so the files were not compared",
            fs_name(expected_erofs),
            fs_name(actual_erofs)
        );
        return Ok(());
    }
    erofs::require_tools()?;
    // Extract next to the published image, where there is room.
    let work_dir = images
        .actual_path
        .parent()
        .filter(|d| !d.as_os_str().is_empty())
        .unwrap_or(Path::new("."));
    let files = (|| {
        // Compressed files can expand to any size, so bound them before extracting.
        let expected_size = erofs::total_file_size(&images.expected_path, p.offset)?;
        let actual_size = erofs::total_file_size(&images.actual_path, p.offset)?;
        eventlog::event(
            "erofs-file-size",
            json!({
                "rebuilt_bytes": expected_size,
                "published_bytes": actual_size,
                "published_limit": expected_size.saturating_add(p.len),
            }),
        );
        ensure_whatever!(
            actual_size <= expected_size.saturating_add(p.len),
            "the published ROOT-A holds {actual_size} bytes of files, more than the rebuilt \
             ROOT-A ({expected_size} bytes) plus the size of the partition; it was not \
             extracted"
        );
        let e = ErofsTree::extract(&images.expected_path, p.offset, p.len, work_dir)?;
        let a = ErofsTree::extract(&images.actual_path, p.offset, p.len, work_dir)?;
        fsfiles::compare_trees(&e, &a, Rules::Root, p.len)
    })();
    match files {
        Ok(files) => {
            let mismatches = files
                .iter()
                .filter(|f| f.status == FileStatus::Mismatch)
                .count();
            if files.is_empty() {
                r.detail = "contents differ, but all entries are identical; the difference is in \
                            what is not compared (timestamps or filesystem layout)"
                    .to_string();
            } else if mismatches == 0 {
                r.status = Status::ExpectedDifference;
                r.detail = format!(
                    "files differ only in kernel module signatures, the TUF root role and the SBOMs; {} differing files listed",
                    files.len()
                );
            } else {
                r.detail = format!(
                    "{mismatches} of {} differing files differ beyond kernel module signatures, the TUF root role and the SBOMs",
                    files.len()
                );
            }
            r.files = files;
        }
        Err(e) => {
            eventlog::event("error", json!({ "error": e.to_string() }));
            r.detail = format!("contents differ and files could not be read: {e}");
        }
    }
    Ok(())
}

/// Compare a boot partition whose bytes differ file by file. It fails unless
/// every difference is signing-dependent.
fn explain_boot_files(expected: &fsfiles::Files, actual: &fsfiles::Files, r: &mut RegionReport) {
    r.files = fsfiles::compare_files(expected, actual, Rules::Boot);
    let mismatches = r
        .files
        .iter()
        .filter(|f| f.status == FileStatus::Mismatch)
        .count();
    if r.files.is_empty() {
        r.detail = "contents differ, but all files are identical; the difference is in what is \
                    not compared (timestamps, attributes, ownership, permissions, extended \
                    attributes or filesystem layout)"
            .to_string();
    } else if mismatches == 0 {
        r.status = Status::ExpectedDifference;
        r.detail = "files differ only in signing-dependent content".to_string();
    } else {
        r.detail = format!(
            "{mismatches} of {} differing files differ beyond signatures, embedded keys and the \
             verity root hash and salt",
            r.files.len()
        );
    }
}

/// The bootconfig GRUB loads from PRIVATE at boot, without checking a signature.
const BOOTCONFIG: &str = "/bootconfig.data";

/// Lines of `bootconfig.data` shown per side when it differs.
const MAX_SHOWN_BOOTCONFIG_LINES: usize = 10;

/// The text of a `bootconfig.data`, without the footer `bootconfig -a` appends.
fn bootconfig_text(data: &[u8]) -> String {
    let text = data
        .strip_suffix(b"#BOOTCONFIG\n")
        .and_then(|d| d.get(..d.len().checked_sub(8)?))
        .unwrap_or(data);
    String::from_utf8_lossy(text)
        .trim_end_matches('\0')
        .to_string()
}

/// The lines only in the rebuilt and only in the published `bootconfig.data`.
fn bootconfig_diff(expected: &[u8], actual: &[u8]) -> String {
    let (expected, actual) = (bootconfig_text(expected), bootconfig_text(actual));
    let only = |of: &str, other: &str| {
        let other: BTreeSet<&str> = other.lines().collect();
        let lines: Vec<String> = of
            .lines()
            .filter(|l| !other.contains(l))
            .map(|l| format!("{l:?}"))
            .collect();
        let mut shown = lines
            .iter()
            .take(MAX_SHOWN_BOOTCONFIG_LINES)
            .cloned()
            .collect::<Vec<_>>()
            .join(", ");
        if lines.len() > MAX_SHOWN_BOOTCONFIG_LINES {
            shown.push_str(&format!(
                " and {} more",
                lines.len() - MAX_SHOWN_BOOTCONFIG_LINES
            ));
        }
        if shown.is_empty() {
            "none".to_string()
        } else {
            shown
        }
    };
    format!(
        "lines only in the rebuilt bootconfig: {}; only in the published one: {}",
        only(&expected, &actual),
        only(&actual, &expected)
    )
}

/// Explain how PRIVATE differs from the rebuilt one. It fails unless it differs
/// only in the directory hash flags, which mke2fs takes from the build host.
fn explain_private(images: &mut Images, p: &Partition, r: &mut RegionReport) {
    let _scope = eventlog::region(&p.name);
    let result = (|| -> Result<_> {
        let (e, a) = images.read(p)?;
        let flags = (
            fsfiles::ext4_dir_hash_flags(&e)?,
            fsfiles::ext4_dir_hash_flags(&a)?,
        );
        // The rebuilt PRIVATE as a build host with the published one's `char` signedness writes it.
        let same_beyond_flags = flags.0 != flags.1 && {
            let mut e = e.clone();
            fsfiles::ext4_copy_dir_hash_flags(&mut e, &a)?;
            e == a
        };
        let (e, a) = (fsfiles::ext4_files(e)?, fsfiles::ext4_files(a)?);
        let mut files = fsfiles::compare_files(&e, &a, Rules::Exact);
        let bootconfig = BOOTCONFIG.as_bytes();
        if let (Some(f), Some(e), Some(a)) = (
            files.iter_mut().find(|f| f.path == BOOTCONFIG),
            e.get(bootconfig),
            a.get(bootconfig),
        ) {
            f.detail = format!("{}; {}", f.detail, bootconfig_diff(e, a));
        }
        Ok((flags, same_beyond_flags, files))
    })();
    let ((expected, actual), same_beyond_flags, files) = match result {
        Ok(result) => result,
        Err(e) => {
            eventlog::event("error", json!({ "error": e.to_string() }));
            r.detail = format!("contents differ and files could not be read: {e}");
            return;
        }
    };
    let (expected, actual) = (
        fsfiles::dir_hash_signedness(expected),
        fsfiles::dir_hash_signedness(actual),
    );
    eventlog::event(
        "dir-hash",
        json!({
            "rebuilt": expected,
            "published": actual,
            "same_beyond_dir_hash_flags": same_beyond_flags,
        }),
    );
    let mut details = Vec::new();
    if expected != actual {
        let name = |s: Option<&'static str>| s.unwrap_or("not recorded");
        details.push(format!(
            "directory hashes are {} in the rebuilt PRIVATE but {} in the published one, which \
             mke2fs takes from the build host (signed on x86_64, unsigned on aarch64)",
            name(expected),
            name(actual)
        ));
    }
    if same_beyond_flags {
        r.status = Status::ExpectedDifference;
        r.detail = format!(
            "differs only in its directory hash flags: {}; with the published flags, the rebuilt \
             PRIVATE matches it byte for byte",
            details.join("; ")
        );
        r.files = files;
        return;
    }
    match files.len() {
        0 if expected != actual => details.push(
            "with the published flags, the rebuilt PRIVATE still differs, in what is not \
             compared (ownership, permissions, extended attributes such as SELinux labels, \
             timestamps or filesystem layout)"
                .to_string(),
        ),
        0 => {}
        1 => details.push(format!("{} differs", files[0].path)),
        n => details.push(format!("{n} files differ")),
    }
    r.detail = if details.is_empty() {
        "contents differ, but the directory hash flags and the files are identical; the \
         difference is in what is not compared (ownership, permissions, extended attributes \
         such as SELinux labels, timestamps or filesystem layout)"
            .to_string()
    } else {
        format!("contents differ: {}", details.join("; "))
    };
    r.files = files;
}

/// Where an image's kernel command line comes from.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum BootSource {
    /// `/grub/grub.cfg` in BOOT-A, which GRUB boots.
    Grub,
    /// The `.cmdline` section of the UKI in EFI-A; UKI images have no BOOT-A.
    Uki,
}

impl BootSource {
    fn of(layout: &DiskLayout) -> Self {
        if layout.find("BOOT-A").is_some() {
            Self::Grub
        } else {
            Self::Uki
        }
    }

    /// The partition the boot configuration is read from.
    fn partition(self) -> &'static str {
        match self {
            Self::Grub => "BOOT-A",
            Self::Uki => "EFI-A",
        }
    }

    fn name(self) -> &'static str {
        match self {
            Self::Grub => "grub.cfg",
            Self::Uki => "UKI kernel command line",
        }
    }

    /// Read the boot configuration from the files of `partition()`.
    fn read(self, files: &fsfiles::Files) -> BootConfigData {
        match self {
            Self::Grub => files
                .get(fsfiles::GRUB_CFG)
                .cloned()
                .ok_or_else(|| "no /grub/grub.cfg".to_string()),
            Self::Uki => uki_cmdline(files),
        }
    }
}

/// A boot configuration, or why it could not be read.
type BootConfigData = std::result::Result<Vec<u8>, String>;

/// The single `.cmdline` section of the single UKI in EFI-A.
fn uki_cmdline(files: &fsfiles::Files) -> BootConfigData {
    let ukis: Vec<_> = files
        .iter()
        .filter(|(path, _)| fsfiles::is_uki_path(path))
        .collect();
    let (path, uki) = match ukis.as_slice() {
        [uki] => *uki,
        [] => return Err(format!("no UKI at {}", fsfiles::UKI_PATHS.join(" or "))),
        _ => {
            let paths: Vec<_> = ukis.iter().map(|(p, _)| fsfiles::display(p)).collect();
            return Err(format!("more than one UKI ({})", paths.join(", ")));
        }
    };
    let path = fsfiles::display(path);
    let sections = pcrsys::pe::sections(uki)
        .map_err(|e| format!("failed to read the PE sections of {path}: {e}"))?;
    let cmdlines: Vec<_> = sections
        .iter()
        .filter(|(name, _)| name == fsfiles::CMDLINE_SECTION)
        .collect();
    match cmdlines.as_slice() {
        [(_, cmdline)] => Ok(cmdline.to_vec()),
        [] => Err(format!(
            "{path} has no {} section",
            fsfiles::CMDLINE_SECTION
        )),
        _ => Err(format!(
            "{path} has {} {} sections",
            cmdlines.len(),
            fsfiles::CMDLINE_SECTION
        )),
    }
}

/// The boot configuration of both images, as BOOT-CONFIG checks it.
#[derive(Debug)]
struct BootConfig {
    source: BootSource,
    rebuilt: BootConfigData,
    published: BootConfigData,
}

impl BootConfig {
    /// A boot configuration whose partition is missing or unreadable.
    fn unread(source: BootSource) -> Self {
        let why = "the partition is missing or its files could not be read".to_string();
        Self {
            source,
            rebuilt: Err(why.clone()),
            published: Err(why),
        }
    }

    /// Read the boot configuration from the files of `source.partition()`.
    fn read(source: BootSource, expected: &fsfiles::Files, actual: &fsfiles::Files) -> Self {
        Self {
            source,
            rebuilt: source.read(expected),
            published: source.read(actual),
        }
    }
}

/// Check that the published boot configuration matches the rebuilt one except
/// for the verity root hash and salt, with a single verity table for the same
/// devices, and return the published table.
fn check_boot_config(config: &BootConfig) -> Result<VerityTable> {
    let (source, name) = (config.source, config.source.name());
    let read = |side: &str, data: &BootConfigData| -> Result<Vec<u8>> {
        match data {
            Ok(data) => Ok(data.clone()),
            Err(e) => {
                snafu::whatever!(
                    "failed to read the {side} {name} from {}: {e}",
                    source.partition()
                );
            }
        }
    };
    let expected = read("rebuilt", &config.rebuilt)?;
    let actual = read("published", &config.published)?;
    let same_beyond_verity =
        fsfiles::normalize_verity(&expected) == fsfiles::normalize_verity(&actual);
    eventlog::event(
        "boot-config",
        json!({
            "source": name,
            "rebuilt_sha256": hex::encode(Sha256::digest(&expected)),
            "published_sha256": hex::encode(Sha256::digest(&actual)),
            "same_beyond_verity_digests": same_beyond_verity,
        }),
    );
    ensure_whatever!(
        same_beyond_verity,
        "the published {name} differs from the rebuilt one beyond the verity root hash and salt"
    );
    let table = |data: &[u8], side: &str| -> Result<VerityTable> {
        // The whole file, not just the parsed command line, must hold one table.
        let table = VerityTable::find_unique(data)
            .with_whatever_context(|_| format!("invalid {side} {name}"))?;
        match source {
            BootSource::Uki => Ok(table),
            BootSource::Grub => {
                let cmdline = pcrsys::parsers::grub::parse(data)
                    .whatever_context(format!("failed to parse the {side} grub.cfg"))?;
                VerityTable::find_unique(cmdline.as_bytes())
                    .with_whatever_context(|_| format!("invalid {side} kernel command line"))
            }
        }
    };
    let rebuilt = table(&expected, "rebuilt")?;
    let published = table(&actual, "published")?;
    eventlog::event(
        "verity-tables",
        json!({ "rebuilt": rebuilt.to_json(), "published": published.to_json() }),
    );
    ensure_whatever!(
        VerityTable {
            root_hash: rebuilt.root_hash.clone(),
            salt: rebuilt.salt.clone(),
            ..published.clone()
        } == rebuilt,
        "the published verity table differs from the rebuilt one beyond the root hash and salt"
    );
    Ok(published)
}

fn boot_config_region(
    boot: Option<&Partition>,
    config: &BootConfig,
    result: &Result<VerityTable>,
) -> RegionReport {
    let sha256 = |f: &BootConfigData| f.as_ref().ok().map(|f| hex::encode(Sha256::digest(f)));
    let name = config.source.name();
    let (status, detail) = match result {
        Ok(_) if config.rebuilt == config.published => (Status::Match, format!("{name} identical")),
        Ok(table) => (
            Status::ExpectedDifference,
            format!(
                "{name} differs only in the verity root hash and salt; the published image boots \
                 ROOT-A ({}) and HASH-A ({}) with root hash {}",
                table.data_device,
                table.hash_device,
                hex::encode(&table.root_hash)
            ),
        ),
        Err(e) => (Status::Mismatch, e.to_string()),
    };
    RegionReport {
        name: "BOOT-CONFIG".to_string(),
        policy: Policy::BootConfig,
        status,
        fatal: true,
        offset: boot.map_or(0, |p| p.offset),
        len: boot.map_or(0, |p| p.len),
        expected_sha256: sha256(&config.rebuilt),
        actual_sha256: sha256(&config.published),
        detail,
        files: Vec::new(),
    }
}

/// Compare the data image over the rebuilt image's length, and check that the rest is zero.
pub fn compare_data(expected: &Path, actual: &Path) -> Result<ImageReport> {
    let mut images = Images::open(expected, actual)?;
    let expected_len = disk::file_len(&images.expected)?;
    let actual_len = disk::file_len(&images.actual)?;
    let mut report = ImageReport {
        expected: Some(expected.to_path_buf()),
        actual: Some(actual.to_path_buf()),
        expected_len,
        actual_len,
        regions: Vec::new(),
    };
    eventlog::event(
        "image",
        json!({
            "image": "data",
            "rebuilt": expected,
            "published": actual,
            "rebuilt_len": expected_len,
            "published_len": actual_len,
        }),
    );
    let common = [(0, expected_len.min(actual_len))];
    let (e, a) = images.hash(&common)?;
    let mut r = assess_region("DATA", Policy::MustMatch, &common, Some(&e), &a);
    if actual_len < expected_len {
        r.status = Status::Mismatch;
        r.detail = format!(
            "published image ({actual_len} bytes) is smaller than the rebuilt image ({expected_len} bytes)"
        );
    }
    report.regions.push(r);
    if actual_len > expected_len {
        let tail = [(expected_len, actual_len - expected_len)];
        let a = disk::hash_ranges(&mut images.actual, &tail)?;
        report.regions.push(assess_region(
            "PADDING",
            Policy::MustBeZero,
            &tail,
            None,
            &a,
        ));
    }
    Ok(report)
}

/// Report a data image that exists on only one side, which fails verification.
fn missing_data(expected: Option<&Path>, actual: Option<&Path>) -> Result<ImageReport> {
    let Some(path) = expected.or(actual) else {
        snafu::whatever!("no data image given");
    };
    let detail = if expected.is_some() {
        "the rebuild produced a data image, but the AMI has no data volume"
    } else {
        "the AMI has a data volume, but the rebuild produced no data image"
    };
    let len = disk::file_len(
        &File::open(path).whatever_context(format!("failed to open {}", path.display()))?,
    )?;
    Ok(ImageReport {
        expected: expected.map(Path::to_path_buf),
        actual: actual.map(Path::to_path_buf),
        expected_len: if expected.is_some() { len } else { 0 },
        actual_len: if actual.is_some() { len } else { 0 },
        regions: vec![RegionReport {
            name: "DATA".to_string(),
            policy: Policy::MustMatch,
            status: Status::Mismatch,
            fatal: true,
            offset: 0,
            len,
            expected_sha256: None,
            actual_sha256: None,
            detail: detail.to_string(),
            files: Vec::new(),
        }],
    })
}

/// Log the outcome of every region of `report`.
fn log_results(image: &str, report: &ImageReport) {
    for r in &report.regions {
        let _scope = eventlog::region(&r.name);
        eventlog::event(
            "result",
            json!({
                "image": image,
                "policy": r.policy,
                "status": r.status,
                "fatal": r.fatal,
                "offset": r.offset,
                "len": r.len,
                "detail": r.detail,
                "listed_files": r.files.len(),
            }),
        );
    }
}

/// Compare the OS image and the data images.
pub fn compare(
    expected: &Path,
    actual: &Path,
    expected_data: Option<&Path>,
    actual_data: Option<&Path>,
) -> Result<Report> {
    eventlog::event(
        "start",
        json!({
            "rebuilt": expected,
            "published": actual,
            "rebuilt_data": expected_data,
            "published_data": actual_data,
        }),
    );
    let os = compare_os(expected, actual)?;
    log_results("os", &os);
    let data = match (expected_data, actual_data) {
        (Some(e), Some(a)) => Some(compare_data(e, a)?),
        (None, None) => None,
        (e, a) => Some(missing_data(e, a)?),
    };
    if let Some(data) = &data {
        log_results("data", data);
    }
    let failed = os.failed() || data.as_ref().is_some_and(ImageReport::failed);
    let failed_regions: Vec<String> = std::iter::once(("os", &os))
        .chain(data.as_ref().map(|d| ("data", d)))
        .flat_map(|(image, r)| {
            r.regions
                .iter()
                .filter(|r| r.failed())
                .map(move |r| format!("{image}/{}", r.name))
        })
        .collect();
    eventlog::event(
        "verdict",
        json!({
            "verdict": if failed { Verdict::Failed } else { Verdict::Verified },
            "failed_regions": failed_regions,
        }),
    );
    Ok(Report {
        verdict: if failed {
            Verdict::Failed
        } else {
            Verdict::Verified
        },
        os,
        data,
        notes: NOTES.iter().map(|s| s.to_string()).collect(),
    })
}

